import { execFileSync } from 'node:child_process';
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { afterAll, describe, expect, it } from 'vitest';
import { byPath } from './report-model.ts';
import {
  DIFF_FLAGS,
  isOnChangedLine,
  parseChangedLines,
  parseHunkHeader,
} from './changed-lines.ts';

/**
 * The gate's failure scope, one level down: which LINES the branch added or modified. Everything the
 * verdict decides is joined against this, so a parser that reads a hunk header wrongly does not
 * crash — it produces a *wrong gate*, silently, in whichever direction the mistake leans.
 *
 * Two of the scenarios here are the two forms `git diff -U0` actually emits and one of them is a
 * trap: `@@ -a,b +c,0 @@` is a pure DELETION, and reading it as the range `c-c` would gate the
 * branch on a line it never touched. So the fixtures are generated by running real `git diff` over a
 * real repository rather than by writing headers out by hand, and the raw text is asserted to
 * contain both forms — a hand-written fixture can only ever pin what its author already believed.
 */

const GIT_ENV = [
  '-c',
  'user.email=test@example.com',
  '-c',
  'user.name=Test',
  '-c',
  'commit.gpgsign=false',
  '-c',
  'init.defaultBranch=main',
];

function git(cwd: string, ...args: readonly string[]): string {
  // The ambient git config is disowned: a developer's global `core.hooksPath` or `init.templateDir`
  // would otherwise run someone else's hooks inside these throwaway repos, and the test would fail
  // on one machine only.
  return execFileSync('git', [...GIT_ENV, ...args], {
    cwd,
    encoding: 'utf8',
    env: { ...process.env, GIT_CONFIG_GLOBAL: '/dev/null', GIT_CONFIG_SYSTEM: '/dev/null' },
  });
}

const workspaces: string[] = [];

afterAll(() => {
  for (const workspace of workspaces) rmSync(workspace, { recursive: true, force: true });
});

/**
 * A throwaway repository with `before` committed and `after` in the working tree, diffed with
 * exactly the flags the CI job passes. `DIFF_FLAGS` is shared with the workflow through
 * `mutation-scope.test.ts`, so this fixture and production cannot drift onto different git output.
 */
function realDiff(files: Readonly<Record<string, { before: string; after: string }>>): string {
  const workspace = mkdtempSync(path.join(tmpdir(), 'changed-lines-'));
  workspaces.push(workspace);
  git(workspace, 'init', '--quiet');
  for (const [name, { before }] of Object.entries(files)) {
    writeFileSync(path.join(workspace, name), before);
  }
  git(workspace, 'add', '.');
  git(workspace, 'commit', '--quiet', '-m', 'base');
  for (const [name, { after }] of Object.entries(files)) {
    writeFileSync(path.join(workspace, name), after);
  }
  return git(workspace, 'diff', ...DIFF_FLAGS, 'HEAD');
}

const numbered = (from: number, to: number): string =>
  Array.from({ length: to - from + 1 }, (_, index) => `line ${from + index}`).join('\n') + '\n';

describe('changed lines, from real git output', () => {
  // One repository, one diff, every shape at once — a single fixture the scenarios below read, so
  // the header forms they claim to cover are provably in the same text git produced.
  const diff = realDiff({
    'edited.ts': {
      // Line 3 rewritten in place: git emits the `d`-absent single-line form for this.
      before: numbered(1, 6),
      after: numbered(1, 6).replace('line 3\n', 'line three\n'),
    },
    'inserted.ts': {
      // Two lines added after line 2, with nothing removed: `@@ -2,0 +3,2 @@`.
      before: numbered(1, 4),
      after: numbered(1, 2) + 'added a\nadded b\n' + numbered(3, 4),
    },
    'deleted-from.ts': {
      // Lines 2 and 3 removed and nothing put back: the `+c,0` pure-deletion form.
      before: numbered(1, 5),
      after: numbered(1, 1) + numbered(4, 5),
    },
    'untouched.ts': { before: numbered(1, 3), after: numbered(1, 3) },
  });

  it('emits both hunk-header forms this parser has to handle', () => {
    // Anti-vacuity: every scenario below is worthless if git did not actually produce the shapes
    // they are about. Asserted against the raw text before anything is parsed.
    expect(diff).toMatch(/^@@ -3 \+3 @@/m); // `d` absent — exactly one line
    expect(diff).toMatch(/^@@ -\d+,\d+ \+\d+,0 @@/m); // a pure deletion
    expect(diff).toMatch(/^@@ -\d+,0 \+\d+,\d+ @@/m); // a pure insertion
  });

  it('reads a single-line hunk whose header omits the line count', () => {
    expect(parseChangedLines(diff).get('edited.ts')).toEqual([{ start: 3, end: 3 }]);
  });

  it('reads an inserted run as the lines it added', () => {
    expect(parseChangedLines(diff).get('inserted.ts')).toEqual([{ start: 3, end: 4 }]);
  });

  it('gates nothing for a pure deletion — the branch added no line there', () => {
    // The trap. `@@ -2,2 +1,0 @@` says two lines left and none arrived; turning it into `1-1`
    // would fail the branch for a survivor on a line it never wrote.
    expect(parseChangedLines(diff).get('deleted-from.ts')).toEqual([]);
  });

  it('still names a file it gates no line in, so a deletion is not an unread file', () => {
    // A deletion-only file is CHANGED (it joins the mutation report, and a scope that joins nothing
    // is a scope nobody audited) while gating no line. One answer for both would make a branch that
    // only deletes code indistinguishable from a broken path join.
    expect(parseChangedLines(diff).has('deleted-from.ts')).toBe(true);
  });

  it('says nothing about a file the branch did not change', () => {
    expect(parseChangedLines(diff).has('untouched.ts')).toBe(false);
  });

  it('keys every changed file in one diff, in the spelling git printed', () => {
    // The join with Stryker's report is by this key. `--no-prefix` is in `DIFF_FLAGS` precisely so
    // the key is the repo-relative path and not `b/`-prefixed; a prefix here would make every
    // intersection false and the gate vacuously green.
    expect(parseChangedLines(diff).keys().toArray().toSorted(byPath)).toEqual([
      'deleted-from.ts',
      'edited.ts',
      'inserted.ts',
    ]);
  });
});

describe('changed lines, from real git output for a new file', () => {
  it('gates every line of a file the branch added', () => {
    const workspace = mkdtempSync(path.join(tmpdir(), 'changed-lines-added-'));
    workspaces.push(workspace);
    git(workspace, 'init', '--quiet');
    writeFileSync(path.join(workspace, 'existing.ts'), numbered(1, 2));
    git(workspace, 'add', '.');
    git(workspace, 'commit', '--quiet', '-m', 'base');
    writeFileSync(path.join(workspace, 'brand-new.ts'), numbered(1, 3));
    git(workspace, 'add', '.');
    const diff = git(workspace, 'diff', ...DIFF_FLAGS, 'HEAD');

    // A new file's `---` side is `/dev/null`; the parser must key it off the `+++` side or lose
    // every line of every file the branch introduced.
    expect(parseChangedLines(diff).get('brand-new.ts')).toEqual([{ start: 1, end: 3 }]);
  });
});

describe('hunk headers', () => {
  it('reads `@@ -a,b +c,d @@` as the d lines starting at c', () => {
    expect(parseHunkHeader('@@ -44,25 +44,25 @@ function foo() {')).toEqual({ start: 44, end: 68 });
  });

  it('reads a header with no new-side count as exactly one line', () => {
    expect(parseHunkHeader('@@ -85 +85 @@')).toEqual({ start: 85, end: 85 });
  });

  it('reads a zero new-side count as no gated line at all', () => {
    expect(parseHunkHeader('@@ -12,3 +11,0 @@')).toBeUndefined();
  });

  it('reads a line that is not a hunk header as no hunk', () => {
    // The parser walks every line of the diff, and a context or content line beginning `@@` inside
    // a source file must not be mistaken for a header that moves the gate.
    expect(parseHunkHeader('+const banner = "@@ -1 +1 @@";')).toBeUndefined();
    expect(parseHunkHeader('diff --git edited.ts edited.ts')).toBeUndefined();
  });
});

describe('diff content that looks like diff syntax', () => {
  it('does not read an added line beginning `++ ` as a new file header', () => {
    // Under `-U0` every line inside a hunk is added or removed, and an ADDED line whose content
    // starts with `++ ` is printed as `+++ ` — indistinguishable from a file header by shape alone.
    // Misreading one re-keys every hunk after it onto a file that does not exist, which moves the
    // gate off the real file silently: no findings, and the whole thing reads as clean.
    const diff = [
      'diff --git real.ts real.ts',
      '--- real.ts',
      '+++ real.ts',
      '@@ -7 +7 @@',
      '+++ not/a/file.ts',
      '@@ -20 +20 @@',
      '+const x = 1;',
    ].join('\n');

    const changed = parseChangedLines(diff);

    expect(changed.keys().toArray()).toEqual(['real.ts']);
    expect(changed.get('real.ts')).toEqual([
      { start: 7, end: 7 },
      { start: 20, end: 20 },
    ]);
  });

  it('does not read a removed line beginning `-- ` as a header pair', () => {
    const diff = [
      'diff --git real.ts real.ts',
      '--- real.ts',
      '+++ real.ts',
      '@@ -7,2 +7 @@',
      '--- not/a/file.ts',
      '+++ also/not/a/file.ts',
    ].join('\n');

    expect(parseChangedLines(diff).keys().toArray()).toEqual(['real.ts']);
  });
});

describe('a diff with nothing in it', () => {
  it('reads an empty diff as no changed line anywhere', () => {
    expect(parseChangedLines('').size).toBe(0);
  });

  it('names a mode-only change but gates no line in it', () => {
    // git emits no `---`/`+++` pair for a mode change or a pure rename, yet `--diff-filter=ACMR`
    // keeps such a file in the mutate scope — so it reaches the report. A parser that never named
    // it would leave a reported file joining nothing, and the verdict would rightly refuse, over a
    // branch that did nothing wrong. Named, with no ranges: changed, gating nothing.
    const modeOnly = ['diff --git edited.ts edited.ts', 'old mode 100644', 'new mode 100755'].join(
      '\n',
    );

    expect(parseChangedLines(modeOnly).get('edited.ts')).toEqual([]);
  });

  it('names the destination of a pure rename', () => {
    const renamed = [
      'diff --git old.ts new.ts',
      'similarity index 100%',
      'rename from old.ts',
      'rename to new.ts',
    ].join('\n');

    expect(parseChangedLines(renamed).keys().toArray()).toEqual(['new.ts']);
  });
});

describe('overlap, not containment', () => {
  const hunk = [{ start: 20, end: 21 }] as const;

  it('counts a span that sits inside a changed hunk', () => {
    expect(isOnChangedLine(hunk, { start: 20, end: 20 })).toBe(true);
  });

  it('counts a span that encloses the changed hunk', () => {
    // The whole point of post-filtering rather than range-scoping the run: Stryker's own filter is
    // containment, so a block mutant spanning lines 10-40 is never even generated for a 20-21
    // range. Here it counts, because the spans overlap.
    expect(isOnChangedLine(hunk, { start: 10, end: 40 })).toBe(true);
  });

  it('counts a span that starts before the hunk and ends inside it', () => {
    expect(isOnChangedLine(hunk, { start: 15, end: 20 })).toBe(true);
  });

  it('counts a span that starts inside the hunk and ends after it', () => {
    expect(isOnChangedLine(hunk, { start: 21, end: 30 })).toBe(true);
  });

  it('does not count a span abutting the hunk without touching it', () => {
    expect(isOnChangedLine(hunk, { start: 1, end: 19 })).toBe(false);
    expect(isOnChangedLine(hunk, { start: 22, end: 40 })).toBe(false);
  });

  it('does not count any span in a file the branch did not change', () => {
    expect(isOnChangedLine(undefined, { start: 1, end: 1000 })).toBe(false);
  });

  it('counts a span overlapping any one of several hunks', () => {
    const hunks = [
      { start: 5, end: 5 },
      { start: 20, end: 21 },
    ];

    expect(isOnChangedLine(hunks, { start: 21, end: 21 })).toBe(true);
    expect(isOnChangedLine(hunks, { start: 10, end: 11 })).toBe(false);
  });
});
